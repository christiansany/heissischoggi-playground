#!/usr/bin/env bash
# Generates results/<HC_VERSION>/REPORT.md from the files repro.sh wrote:
# every operation of every style, with its result per composition and the
# operation plan wherever the gateway produced one.
set -euo pipefail
cd "$(dirname "$0")/.."
HC_VERSION="${HC_VERSION:-16.7.7}"
ROOT="results/$HC_VERSION"
# Hashes and ids differ per run and add nothing; the raw plans are in *.plan.json.
STRIP='del(.id) | walk(if type == "object" then del(.hash, .shortHash, .xxHash) else . end)'

result_of() { # style composition operation
  awk -v op="$3" '$1 == op { $1 = ""; $2 = ""; sub(/^ +/, ""); print }' "$ROOT/$1/$2/summary.txt"
}

{
  echo "# Results for Hot Chocolate $HC_VERSION"
  echo
  echo "Generated by \`scripts/report.sh\` from the files in this folder. Do not edit by hand."
  echo
  echo "Plans are shown without hashes and ids. Raw files: \`<style>/<composition>/<operation>.plan.json\` and \`.response.txt\`."

  for style in new-style old-style; do
    echo
    echo "## $style"
    echo
    COMPOSITIONS=(catalog-only catalog+reviews)
    [ -d "$ROOT/$style/catalog+reviews+assistance" ] && COMPOSITIONS+=(catalog+reviews+assistance)
    header="| Operation |"; rule="|---|"
    for composition in "${COMPOSITIONS[@]}"; do header="$header $composition |"; rule="$rule---|"; done
    echo "$header"
    echo "$rule"
    for file in "operations/$style"/*.graphql; do
      op="$(basename "$file" .graphql)"
      row="| [$op](#$style-$op) |"
      for composition in "${COMPOSITIONS[@]}"; do row="$row $(result_of "$style" "$composition" "$op") |"; done
      echo "$row"
    done

    for file in "operations/$style"/*.graphql; do
      op="$(basename "$file" .graphql)"
      echo
      echo "### <a id=\"$style-$op\"></a>$style / $op"
      echo
      echo '```graphql'
      cat "$file"
      echo '```'
      for composition in "${COMPOSITIONS[@]}"; do
        dir="$ROOT/$style/$composition"
        echo
        echo "**$composition:** $(result_of "$style" "$composition" "$op")"
        echo
        if [ -f "$dir/$op.plan.json" ]; then
          echo "<details><summary>Operation plan</summary>"
          echo
          echo '```json'
          jq "$STRIP" "$dir/$op.plan.json"
          echo '```'
          echo
          echo "</details>"
        else
          echo "No operation plan: the request failed before a plan existed."
        fi
      done
    done
  done
} > "$ROOT/REPORT.md"
echo "wrote $ROOT/REPORT.md"
